//! Mods build only: the mods' animated models (skinned glTF files) made into skeletal meshes and
//! animations of the game (openxiii_assets::mod_skeletal), when the game starts.

use std::collections::HashMap;
use std::sync::Arc;

use openxiii_assets::mod_skeletal::{BoneIn, ClipIn, Frame, ModAnimation, ModSkeletal};
use openxiii_assets::mod_textures::Mips;
use openxiii_mods::own_animated::{self, SAMPLE_RATE};
use openxiii_mods::own_models::OwnModel;

impl crate::Vm {
    /// Markdown reference of the game's animations (docs/modding/animations.md): for each
    /// animation of the weapons seen in first person and of the characters, the classes and
    /// meshes that use it, the bones of those meshes, and its sequences with their length,
    /// rate and notifies. The names a mod's animated model must give (`[models.<Name>.animations]`
    /// and `[models.<Name>.bones]`) for the game's scripts to animate it.
    pub fn animations_reference(&mut self) -> Result<String, String> {
        let weapon = self.class("XIII.XIIIWeapon").ok_or("class XIIIWeapon not found")?;
        let pawn = self.class("Engine.Pawn").ok_or("class Pawn not found")?;
        let mut out = String::new();
        out.push_str("# Animation reference\n\n");
        out.push_str("All the names a mod can use: [names/](names/README.md).\n\n");
        out.push_str("Generated by `oxiii mods-reference <game folder> docs/modding` (oxiii built with `--features mods`)\n");
        out.push_str("from the original game: the animations of the weapons seen in first person and of the\n");
        out.push_str("characters, with the bones of their meshes. A mod's animated model used in their place gives\n");
        out.push_str("the same names: `[models.<Name>.animations]` makes these animations from the model's glTF\n");
        out.push_str("animations, `[models.<Name>.bones]` gives these bone names to its bones (see\n");
        out.push_str("[expert/textures-and-models.md](expert/textures-and-models.md#animated-models)). The game's scripts play the animations by name: one\n");
        out.push_str("that the model does not have is not played, and the log says so.\n\n");
        out.push_str("Lengths are in frames at the sequence's rate (frames per second); notifies are the script\n");
        out.push_str("functions called at a fraction (0 to 1) of the sequence.\n\n");
        for (title, root, skip) in [("Weapons in first person", weapon, vec!["XIIIMP"]), ("Characters", pawn, vec!["XIIIMP", "Engine"])] {
            out.push_str(&format!("## {title}\n\n"));
            let mut classes = vec![root];
            classes.extend((0..self.classes.len()).filter(|&c| c != root && self.is_child_of(c, root)).filter(|&c| !skip.iter().any(|s| self.packages[self.classes[c].package].name.eq_ignore_ascii_case(s))));
            // Animation → (classes, meshes).
            let mut sets: std::collections::BTreeMap<String, (Vec<String>, Vec<String>)> = std::collections::BTreeMap::new();
            for c in classes {
                self.create_cdo(c);
                // A weapon names its first-person mesh in MeshName (loaded by name when it is
                // drawn); other classes give their Mesh.
                let cdo = self.classes[c].cdo;
                let mesh = match (self.prop(cdo, "MeshName"), self.prop(cdo, "Mesh")) {
                    (crate::value::Value::Str(m), _) if !m.is_empty() => m,
                    (_, crate::value::Value::Asset(m)) => m,
                    _ => continue,
                };
                let Some(info) = self.mesh_info(&mesh) else { continue };
                let Some(anim) = info.default_anim.clone() else { continue };
                let entry = sets.entry(anim).or_default();
                entry.0.push(self.class_path(c));
                if !entry.1.contains(&mesh) {
                    entry.1.push(mesh);
                }
            }
            for (anim, (mut users, meshes)) in sets {
                let Some(set) = self.anim_set(&anim) else { continue };
                users.sort_by_key(|u| u.to_lowercase());
                out.push_str(&format!("### {anim}\n\nUsed by: {}\n\nMeshes: {}\n\n", users.join(", "), meshes.join(", ")));
                for mesh in &meshes {
                    if let Some(info) = self.mesh_info(mesh) {
                        out.push_str(&format!("Bones of {mesh}: {}\n\n", info.bones.join(", ")));
                    }
                }
                out.push_str("| Animation | Frames | Rate | Notifies |\n|---|---|---|---|\n");
                for s in &set.seqs {
                    let notifies: Vec<String> = s.notifies.iter().map(|(t, f)| format!("{f} at {t:.2}")).collect();
                    out.push_str(&format!("| {} | {} | {} | {} |\n", s.name, s.num_frames, s.rate, notifies.join(", ")));
                }
                out.push('\n');
            }
        }
        Ok(out)
    }
}

/// An animated model (`m.file` has a skin) as a skeletal mesh of the game, named
/// "Mod.<Name>", and its animation "Mod.<Name>.Animation". Each part's PNG becomes the texture
/// "Mod.<Name>.<part>" (added to `textures`), unless the model names a game `material`. The
/// game animations are made from the glTF animations named in `animations` (with their
/// notifies); the other glTF animations keep their own names. `log` receives the lines for the
/// game's log.
pub fn build_animated_model(m: &OwnModel, textures: &mut HashMap<String, Arc<Mips>>, log: &mut Vec<String>) -> Result<(ModSkeletal, ModAnimation), String> {
    let model = own_animated::load_animated_gltf(&m.file, m.scale)?;
    let mut parts = Vec::new();
    for (i, p) in model.parts.iter().enumerate() {
        let mut material = m.material.clone().unwrap_or_default();
        if let (Some(png), None) = (&p.texture, &m.material) {
            match openxiii_mods::own_textures::decode_png(png) {
                Ok(t) => {
                    material = format!("{}.{i}", m.mesh_name());
                    textures.insert(material.to_ascii_lowercase(), Arc::new(t));
                }
                Err(e) => log.push(format!("warning: model {}: texture {e}; part drawn without it ({})", m.mesh_name(), m.source)),
            }
        }
        parts.push((p.triangles.clone(), material));
    }
    let frames = |f: &[own_animated::Frame]| -> Vec<Frame> { f.iter().map(|x| (x.axes, x.position)).collect() };
    let bones: Vec<BoneIn> = model.bones.iter().map(|b| BoneIn { name: &b.name, parent: b.parent, bind: (b.bind.axes, b.bind.position) }).collect();
    let samples: Vec<Vec<Vec<Frame>>> = model.clips.iter().map(|c| c.samples.iter().map(|s| frames(s)).collect()).collect();
    let mut clips = Vec::new();
    for link in &m.animations {
        match model.clips.iter().position(|c| c.name.eq_ignore_ascii_case(&link.clip)) {
            Some(i) => clips.push(ClipIn { name: &link.game, rate: SAMPLE_RATE, samples: &samples[i], notifies: link.notifies.clone() }),
            None => {
                let names: Vec<&str> = model.clips.iter().map(|c| c.name.as_str()).collect();
                log.push(format!("warning: model {}: animation {} = \"{}\": the file has no such animation (it has: {}) ({})", m.mesh_name(), link.game, link.clip, names.join(", "), m.source));
            }
        }
    }
    for (i, c) in model.clips.iter().enumerate() {
        if !clips.iter().any(|x| x.name.eq_ignore_ascii_case(&c.name)) {
            clips.push(ClipIn { name: &c.name, rate: SAMPLE_RATE, samples: &samples[i], notifies: Vec::new() });
        }
    }
    let animation_name = format!("{}.Animation", m.mesh_name());
    let (mut mesh, animation) = openxiii_assets::mod_skeletal::build(&model.points, &model.uvs, &model.influences, &parts, &bones, &clips, &animation_name)?;
    for (alias, bone) in &m.bones {
        match mesh.bone_names.iter().find(|b| b.eq_ignore_ascii_case(bone)) {
            Some(b) => mesh.aliases.push((alias.clone(), b.clone())),
            None => log.push(format!("warning: model {}: bones: \"{alias}\" = \"{bone}\": the model has no such bone (it has: {}) ({})", m.mesh_name(), mesh.bone_names.join(", "), m.source)),
        }
    }
    let names: Vec<&str> = animation.sequences.iter().map(|s| s.name.as_str()).collect();
    log.push(format!("animated model {} read ({} part(s), {} bone(s), animations: {}) ({})", m.mesh_name(), parts.len(), bones.len(), names.join(", "), m.source));
    Ok((mesh, animation))
}
